"""Write a Singular script that decides whether the initial state is connected to a goal state.

The ring has one variable x(i) for every fact. The script computes a Groebner basis of the ideal
generated by the operator binomials x^pre(o) - x^eff(o) and the goal monomial, and prints
"MEMBER 1" if the initial-state monomial lies in this ideal and "MEMBER 0" otherwise (Theorem 8).
If the goal fixes every variable, the goal monomial is left out of the ideal, and the script tests
whether x^init - x^goal lies in it instead (Theorem 7). This is much faster, because an ideal that
contains the goal monomial contains a monomial for every state connected to the goal.
For members, the script also prints the certificate computed by lift: one line
"TERM j e_1,...,e_N" for every term of the coefficient of the j-th generator, where e_1, ..., e_N
is the exponent vector of the term.

The ideal is homogeneous, so a Groebner basis up to the degree of the state monomials (the number
of variables of the task) suffices, and the script sets degBound accordingly.

The order of the ring variables matters a lot for the size of the Groebner basis. We order the
task variables by reverse Cuthill-McKee on the graph that connects variables mentioned by the same
operator, which places interacting variables close to each other. On 4x4 Lights Out, this reduces
the time for the Groebner basis from 245 s with the translator's order to 2.5 s.

Usage: python3 sas2singular.py task.sas_stnf task.sing
"""

import argparse

from sas import check_supported, read_task


def variable_order(task):
    """Reverse Cuthill-McKee order of the variables, starting each component at a variable of minimum degree."""
    neighbors = [set() for _ in task.variables]
    for op in task.operators:
        mentioned = {var for var, _ in op.prevail} | {var for _, var, _, _ in op.effects}
        for var in mentioned:
            neighbors[var] |= mentioned - {var}
    order, seen = [], set()
    for start in sorted(range(len(task.variables)), key=lambda var: len(neighbors[var])):
        if start in seen:
            continue
        seen.add(start)
        component = [start]
        for var in component:
            for other in sorted(neighbors[var] - seen, key=lambda w: len(neighbors[w])):
                seen.add(other)
                component.append(other)
        order += component
    return order[::-1]


def ring_offsets(task):
    """Fact (var, val) is the ring variable x(offsets[var] + val + 1), with variables in variable_order."""
    offsets, n = [0] * len(task.variables), 0
    for var in variable_order(task):
        offsets[var] = n
        n += len(task.variables[var].values)
    return offsets, n


def binomials(task):
    """The binomials of the operators as pairs (pre facts, eff facts), without duplicates up to sign."""
    seen, result = set(), []
    for op in task.operators:
        pre, eff = set(op.prevail), set(op.prevail)
        for _, var, p, post in op.effects:
            if p == -1:
                raise ValueError(f"operator {op.name!r} is not in STNF: run stnf.py first")
            pre.add((var, p))
            eff.add((var, post))
        key = frozenset([frozenset(pre), frozenset(eff)])
        if pre != eff and key not in seen:
            seen.add(key)
            result.append((sorted(pre), sorted(eff)))
    return result


def is_full_goal(task):
    return len({var for var, _ in task.goal}) == len(task.variables)


def monomial(facts, offsets):
    return "*".join(f"x({offsets[var] + val + 1})" for var, val in facts) or "1"


def singular_script(task, gens, certificate=True, characteristic=32003):
    offsets, n = ring_offsets(task)
    generators = [f"  {monomial(pre, offsets)} - {monomial(eff, offsets)}" for pre, eff in gens]
    target = monomial(enumerate(task.init), offsets)
    if is_full_goal(task):
        target += " - " + monomial(task.goal, offsets)
    else:
        generators.append(f"  {monomial(task.goal, offsets)}")
    lines = [
        f"ring r = {characteristic}, (x(1..{n})), dp;",
        f"degBound = {len(task.variables)};",
        "ideal J =",
        (",\n".join(generators) if generators else "  0") + ";",
        f"poly m0 = {target};",
        "int t0 = rtimer;",
        "ideal G = std(J);",
        'attrib(G, "isSB", 1);  // up to degBound, which suffices for the homogeneous test below',
        'print("STD_MS " + string(rtimer - t0));',
        'print("BASIS_SIZE " + string(size(G)));',
        "int member = (reduce(m0, G) == 0);",
        'print("MEMBER " + string(member));',
    ]
    if certificate:
        lines += [
            "if (member) {",
            "  t0 = rtimer;",
            "  matrix T = lift(J, m0);",
            '  print("LIFT_MS " + string(rtimer - t0));',
            "  int i; int j; poly q;",
            "  for (j = 1; j <= nrows(T); j++) {",
            "    q = T[j, 1];",
            "    for (i = 1; i <= size(q); i++) {",
            '      print("TERM " + string(j) + " " + string(leadexp(q[i])));',
            "    }",
            "  }",
            "}",
        ]
    lines.append("quit;")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("stnf_file")
    parser.add_argument("singular_file")
    parser.add_argument("--no-certificate", action="store_true", help="only decide membership")
    args = parser.parse_args()
    task = read_task(args.stnf_file)
    check_supported(task)
    with open(args.singular_file, "w") as f:
        f.write(singular_script(task, binomials(task), certificate=not args.no_certificate))


if __name__ == "__main__":
    main()
